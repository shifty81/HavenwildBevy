#!/usr/bin/env python3
"""M2D093A regression gate for flat-terrain authority convergence and Terrain Studio."""
from pathlib import Path
import json, re
from source_version_contract import cargo_source_version, project_matches_cargo, source_at_least

ROOT=Path(__file__).resolve().parents[1]
def req(v,msg):
    if not v: raise SystemExit(f"M2D093A SELFTEST: FAIL / {msg}")

def main():
    cargo=(ROOT/'Cargo.toml').read_text()
    project=json.loads((ROOT/'project/forgepy.project.json').read_text())
    world=(ROOT/'src/world_doc.rs').read_text()
    plan=(ROOT/'src/worldgen_plan.rs').read_text()
    auth=(ROOT/'src/asset_authority.rs').read_text()
    main_rs=(ROOT/'src/main.rs').read_text()
    pcc=(ROOT/'ProjectControlCenter.py').read_text()
    profile=json.loads((ROOT/'content/terrain/recipes/summer_flatworld_runtime.v1.json').read_text())
    req(source_at_least(cargo, '0.10.13'), 'Cargo source predates 0.10.13')
    req(project_matches_cargo(project, cargo),'project sourceVersion does not match Cargo')
    req((m:=re.search(r'generated_world\.v(\d+)', world)) is not None and int(m.group(1)) >= 11,'generator predates v11 cache identity')
    plan_runtime=plan.split('#[cfg(test)]',1)[0]
    req('return "WetSand";' not in plan_runtime,'legacy generated WetSand ring returned')
    req('generated_coast_uses_core_sand_without_legacy_wetsand_ring' in plan,'WetSand-ring retirement regression coverage missing')
    req('intended_rivers_open_into_the_ocean' in plan and 'coastal_river_shoulders_use_beach_materials' in plan,'explicit river-mouth regression coverage missing')
    req('|| interior_water(seed, world, island)' in plan,'river-mouth shoulder test does not exclude water cells')
    req('normalized_island_score(seed, neighbour, island) < 9_050' in plan,'MudBank clustering can still validate against coastal Sand')
    world_runtime=world.split('#[cfg(test)]',1)[0]
    req('summer_pale_shore_ring_overlay' in auth,'historical pale-shore evidence family missing')
    req('summer_shoreline_overlay_for_pair(' not in world_runtime,'retired second pale-shore repaint returned to live resolver')
    pale=profile.get('shorelineOverlayFamilies',{}).get('summer_pale_shore_ring_overlay',{})
    req(pale.get('outerRoleCount')==8 and pale.get('innerRoleCount')==4,'pale-shore 12-role source family missing')
    req(pale.get('runtimeUse') in {'certified_source_visual_bridge_for_wetsand','certified_source_visual_family_not_automatic_semantic_fill'},'historical pale-shore evidence contract drifted')
    req('certified_source_visual_bridge_for_wetsand' in auth,'historical pale-shore source validator missing')
    req('if self.contains_source_slice(&candidate)' in auth,'seasonalized object render crops still require exact canonical-region identity')
    req('assert!(authority.contains_source_slice(&cropped_winter_tree));' in auth,'seasonal tree crop regression coverage missing')
    req('if !authority.contains_source_slice(&part.source)' in world,'generated object placement validator still rejects certified alpha source slices')
    quarantine=re.search(r'pub fn quarantine_uncertified_large_objects\(.*?\n    }\n    fn override_mut', world, re.S)
    req(quarantine is not None,'cannot isolate generated-object quarantine implementation')
    req('contains_source_slice(&part.source)' in quarantine.group(0),'startup quarantine still rejects certified alpha source slices')
    req('contains_binding(&part.source)' not in quarantine.group(0),'startup quarantine still uses obsolete exact-binding rule')
    req('.all(|part| a.contains_source_slice(&part.source))' in world,'radius-two Generated World acceptance still expects exact object bindings')
    req('quarantining_large_generated_objects_keeps_certified_slices_and_removes_uncertified_parts' in world,'generated-object quarantine source-slice regression test missing')
    req('.object_template("large_tree_01")' not in world,'quarantine regression calls nonexistent AssetAuthority::object_template helper')
    req('large_tree_01' not in world,'quarantine regression still depends on retired legacy tree template identity')
    req('.templates_with_tag("tree")' in world,'quarantine regression does not select a canonical worldgen-safe tree through public tag authority')
    req('canonical_template_id.clone()' in world,'quarantine regression does not carry the selected canonical template id into generated objects')
    req('canonical.parts[0].source' not in world,'quarantine regression still reads nonexistent TemplatePart.source')
    req('source_asset: canonical_part.source_path.clone()' in world and 'source_rect: canonical_part.source_rect_px' in world,'quarantine regression does not construct SourceBinding from TemplatePart public fields')
    req(not world.endswith('    }\n}\n}\n'),'world_doc.rs has an extra closing delimiter after the tests module')
    req(profile.get('ownerSideTransitions',{}).get('summer_sand_over_wet_sand',{}).get('owner')=='WetSand','WetSand/Sand owner authority missing')
    req('natural_placement_is_clear' in world and 'footprints_overlap' in world,'purpose-object reservation guard missing')
    req('certify_worldgen_object_bounds.py' in pcc,'tree/rock render-bound certification is not in Full Gate')
    req((ROOT/'tools/certify_worldgen_object_bounds.py').is_file(),'worldgen object bounds tool missing')
    bounds=(ROOT/'tools/certify_worldgen_object_bounds.py').read_text()
    req('counts != {"tree": 7, "rock": 2}' in bounds,'tree/rock certification inventory is not locked to 7+2 promoted templates')
    req('"version": 3' in bounds and 'immutable_elizawy_alpha_render_bounds_edge_guide_safe' in bounds,'object render-bound authority is not v3 edge-guide-safe')
    req('_alpha_components' in bounds and 'guideLike' in bounds and 'discardedGuidePixels' in bounds,'slot-edge guide rejection evidence missing')
    mapper=(ROOT/'tools/build_summer_flatworld_mapping.py').read_text()
    req('largest_connected_crop' not in mapper and 'build_certified_object_bounds' in mapper,'terrain mapper still owns a competing tree/rock crop algorithm')
    req((ROOT/'tools/worldgen_object_bounds_algorithm_selftest.py').is_file(),'guide-safe object-bound algorithm regression test missing')
    req('source_uv(rect, sheet)' in main_rs and 'sample two full' not in main_rs,'tree-specific UV inset hack still active')
    req('Live Terrain Rules' in main_rs and 'Terrain Studio · ElizaWy Authority' in main_rs,'Terrain Studio production pattern app missing')
    req('(CanvasTool::Select, "SEL")' not in main_rs and '(CanvasTool::Paint, "PNT")' not in main_rs,'three-letter direct-tool glyphs remain')
    req(main_rs.count('&command_tooltip(') >= 2, 'icon-rail tooltip calls are not borrowed for &str compile contract')
    req('SummerVisualAnimation' in auth and 'animation: None' in auth,'generic canonical animation contract/fallback missing')
    print('M2D093A FLAT TERRAIN CONVERGENCE SELFTEST: PASS')
    print('  coast        : Deep -> Shallow -> Sand -> Grass; legacy generated WetSand ring retired')
    print('  visual bridge: exact Tiled/native-Wang topology first; historical pale-shore family reference-only')
    print('  world intent : purpose-object reservation before ecology')
    print('  objects      : 7 seasonal trees + 2 rocks/stones use v3 edge-guide-safe immutable-alpha bounds')
    print('  tooling      : Unified Terrain Rules + unique icon rail')
    print('  water detail : complete canonical TSX clips may animate; incomplete clips fail closed')
    return 0
if __name__=='__main__': raise SystemExit(main())
